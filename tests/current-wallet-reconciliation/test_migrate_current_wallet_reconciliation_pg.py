#!/usr/bin/env python3
"""Actual PG mechanics, using a fresh disposable Core78 fixture; no rebuild.

Use the same private fixture schema as test_migrate_current_runtime_keys_pg.py,
with a distinct freshly initialized lmm_runtime_keys_test_* database and nonce
COMMENT. Inputs/output belong under the existing I.BACKUP_ROOT; never change
HOME or monkeypatch that boundary. The existing Core78 binary initializes it.

  PYTHONPATH=<wallet-scripts>:<key-scripts>:<fa57>/scripts python \
    test_migrate_current_wallet_reconciliation_pg.py \
    --fixture $HOME/.local/state/lmm-api/<test>/fixture.private.json \
    --output $HOME/.local/state/lmm-api/<test>/wallet-results

Only this explicitly marked synthetic database is changed. This prepares
canonical historical openings, native spending/reservations, signed debt and
an empty new owner, then runs the actual append-only writer. The shared PG
protocol proxy really disconnects before COMMIT and drops a real COMMIT reply.
No production source review or economic approval is generated by these tests.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import json
from pathlib import Path
import time
import uuid

import migrate_current_wallet_reconciliation as W
from test_migrate_current_runtime_keys_pg import Regression, CommitDropProxy, check


class WalletRegression(Regression):
    def source(self, users, archive):
        return {"archive_sha256": archive, "export_sha256": archive, "source_kind": "synthetic-full-export",
                "users": users, "options": [{"key": "CreditsPerUSD", "value": "500000"},
                                            {"key": "QuotaPerUnit", "value": "500000"}],
                "observed_at": 2000, "files": {}}

    def seed_wallets(self):
        self.old_rows = []
        self.current_rows = []
        self.mapping = []
        self.old_positions = [(100, 20, 150, 37), (-100, -5, 50, -7), (60, 0, -10, -4), (0, 0, 0, 0)]
        for index, (old, old_aff, new, new_aff) in enumerate([*self.old_positions, (0, 0, 25, 2)]):
            aid = self.query("INSERT INTO core_identity.accounts(kind) VALUES('personal') RETURNING id")
            uid = self.query("INSERT INTO core_identity.users(personal_account_id) VALUES(" + str(aid) + ") RETURNING id")
            self.run_sql("INSERT INTO core_billing.account_policies(account_id) VALUES(" + str(aid) + ")")
            sid = 5000 + index
            self.mapping.append({"source_user_id": sid, "target_user_id": uid, "target_personal_account_id": aid})
            raw = {"id": sid, "quota": old, "aff_quota": old_aff, "status": 1, "deleted_at": None}
            self.current_rows.append({**raw, "quota": new, "aff_quota": new_aff})
            if index < len(self.old_positions):
                self.old_rows.append(raw)
                payload = {"migration_id": "synthetic-current-wallet-original", "source_entity_key": "legacy.users/" + str(sid),
                    "source_archive_sha256": "b" * 64, "mapping_sha256": "a" * 64,
                    "source_row_sha256": W.digest(raw), "account_id": aid, "available_units": old,
                    "affiliate_units": 0, "reserved_units": 0, "observed_at": 1000}
                self.query("BEGIN ISOLATION LEVEL SERIALIZABLE; SET LOCAL synchronous_commit=on; " +
                    "SELECT core_billing.import_opening_balance(" + W.literal(payload) + "::jsonb); COMMIT;")
        # Actual native actions after the original source opening. They must
        # remain effective after catch-up: the writer must add S-B, not S-N.
        for label, account, kind, amount in (("native-charge", self.mapping[0]["target_personal_account_id"], "charge", 20),
                                            ("native-reserve", self.mapping[0]["target_personal_account_id"], "reserve", 9),
                                            ("native-debt-repayment", self.mapping[1]["target_personal_account_id"], "gift", 20)):
            request = {"scope": "synthetic-native-activity", "operation_key": label,
                       "reason": "Synthetic native activity, not a source migration",
                       "action": {"kind": kind, "account_id": account, "amount_units": amount}}
            self.query("SELECT core_billing.post_ledger(" + W.literal(request) + "::jsonb)")
        self.current_source = self.source(self.current_rows, "c" * 64)
        self.old_source = self.source(self.old_rows, "b" * 64)

    def plan_wallet(self, migration):
        snap = self.query(W.snapshot_sql(self.contract, self.inventory, migration))
        m = W.prepare(self.current_source, [self.old_source], self.mapping, snap, self.contract,
            {"system_identifier": "9988776655", "database": "synthetic_wallet_source", "schema": "synthetic_public"},
            migration, {}, self.fixture["runtime_roles"])
        check(not m["blockers"], "synthetic wallet facts unexpectedly blocked")
        W.F.write_private(self.output, migration + ".preview-" + uuid.uuid4().hex[:12] + ".private.json",
                          W.canonical(m) + "\n")
        return m

    def wallet_proxy(self, m, *, before_commit):
        conn = deepcopy(self.connection)
        path = Path(conn["socket_directory"]) / (".s.PGSQL." + str(conn["port"]))
        directory = self.output / ("proxy-" + uuid.uuid4().hex[:8])
        app = "lmm-current-wallet-" + uuid.uuid4().hex
        with CommitDropProxy(path, directory, conn["port"], before_commit=before_commit):
            conn["socket_directory"] = str(directory)
            code, _, _ = self.run_sql(W.build_sql(m, fixture_nonce=self.nonce),
                                     connection=conn, app=app, expect_ok=False)
            check(code != 0, "disconnected commit unexpectedly acknowledged")
        for _ in range(50):
            active = self.query("SELECT EXISTS(SELECT 1 FROM pg_stat_activity WHERE application_name=" + W.literal(app) + ")")
            if not active:
                break
            time.sleep(0.1)
        check(not active, "original wallet attempt remains active")
        self.wallet_last_application = app
        return self.query(W.resolve_sql(m, app))

    def run(self):
        self.seed_wallets()
        migration = "synthetic-current-wallet-" + uuid.uuid4().hex[:10]
        m = self.plan_wallet(migration)
        first = m["positions"][0]
        second = m["positions"][1]
        check((first["opening_B"], first["native_D"], first["native_N"], first["target_buckets"]["wallet"]) ==
              (100, -29, 71, 121), "wallet source/native delta equation is wrong")
        check(first["target_buckets"]["reserved"] == 9, "reserved funds were not preserved")
        check(second["native_N"] == -80 and second["target_buckets"]["wallet"] == 70
              and second["target_buckets"]["debt"] == 0 and second["target_buckets"]["affiliate"] == -7,
              "signed debt/affiliate target is wrong")
        third = m["positions"][2]
        check(third["legs"]["wallet"] + third["legs"]["debt"] == -70
              and third["target_buckets"]["wallet"] == 0 and third["target_buckets"]["debt"] == -10
              and third["target_buckets"]["affiliate"] == -4,
              "negative wallet correction or signed affiliate was clamped")

        # A real native financial action after preview must fail CAS before
        # the reconciliation allocates IDs, rather than being silently erased.
        account = self.mapping[0]["target_personal_account_id"]
        action = {"scope": "synthetic-native-activity", "operation_key": "native-drift",
                  "reason": "Synthetic drift after preview", "action": {"kind": "charge", "account_id": account, "amount_units": 1}}
        self.query("SELECT core_billing.post_ledger(" + W.literal(action) + "::jsonb)")
        self.reject(W.build_sql(m, fixture_nonce=self.nonce), "wallet_target_state_changed")
        self.completed.append("real_native_financial_drift_rejected_before_reconciliation_allocation")
        m = self.plan_wallet(migration)

        before = self.state(migration)
        resolved = self.wallet_proxy(m, before_commit=True)
        check(resolved["status"] == "UNKNOWN" and resolved["automatic_retry_allowed"] is False,
              "missing receipt was treated as confirmed rollback")
        after = self.state(migration)
        check(after["tables"] == before["tables"], "interrupted wallet migration changed old rows or left new rows")
        for seq in W.SEQUENCES:
            check(after["sequences"][seq]["last_value"] >= before["sequences"][seq]["last_value"], "sequence rewound")
        self.reject(W.build_sql(m, fixture_nonce=self.nonce), "wallet_target_state_changed")
        self.completed.append("real_precommit_disconnect_rolls_back_money_and_receipts_without_sequence_reset")

        # The proxy explicitly proved COMMIT was not sent and the old backend
        # has exited. Refresh the preview after the resulting sequence gaps.
        m = self.plan_wallet(migration)
        resolved = self.wallet_proxy(m, before_commit=False)
        check(resolved["status"] == "COMMITTED", "lost actual COMMIT reply did not resolve")
        committed = self.state(migration)
        self.query(W.build_sql(m, fixture_nonce=self.nonce))
        check(self.state(migration) == committed, "exact replay changes financial rows or consumes IDs")
        self.completed.extend(["actual_commit_reply_loss_resolves_readonly", "exact_replay_preserves_ids_and_money"])
        check(self.query(W.preservation_sql(m)) == m["before_state"]["tables"],
              "old journal/history/reserved/other state was not preserved")
        facts = self.query(W.ledger_facts_sql())
        check(facts["global_valid"] is True, "ledger conservation/entry revisions invalid")
        self.completed.extend(["all_original_rows_preserved_except_expected_trigger_balance_fields",
            "wallet_debt_affiliate_and_clearing_conserve_exact_integer_units",
            "reserved_native_transactions_and_unrelated_funds_remain_intact",
            "negative_affiliate_and_signed_debt_crossing_are_retained",
            "negative_wallet_source_delta_uses_opening_journal_and_creates_exact_signed_debt",
            "new_empty_owner_uses_canonical_initial_opening"])

        # A resolved immutable commit stays committed after legitimate later
        # native activity. Resolving must not confuse its old target balance
        # with the current spendable balance or issue another credit.
        later = {"scope": "synthetic-native-activity", "operation_key": "post-reconcile-native-charge",
                 "reason": "Synthetic later native activity", "action": {"kind": "charge", "account_id": account, "amount_units": 1}}
        self.query("SELECT core_billing.post_ledger(" + W.literal(later) + "::jsonb)")
        after_spending = self.state(migration)
        check(self.query(W.resolve_sql(m, self.wallet_last_application))["status"] == "COMMITTED",
              "later native spending invalidated the immutable committed receipt")
        check(self.state(migration) == after_spending, "read-only commit resolution changes current money")
        self.completed.append("immutable_commit_resolves_after_later_native_spending_without_recredit")

        # After commit, an attempted new epoch must be explicit about its new
        # baseline. It cannot quietly re-add this catch-up as native spending.
        fresh_snapshot = self.query(W.snapshot_sql(self.contract, self.inventory, migration + "-duplicate"))
        duplicate = W.prepare(self.current_source, [self.old_source], self.mapping, fresh_snapshot, self.contract,
            m["source_namespace"], migration + "-duplicate", {}, self.fixture["runtime_roles"])
        check(any(b["code"] == "wallet_source_already_reconciled" for b in duplicate["blockers"]),
              "different batch identity could re-credit the same source")
        self.completed.append("same_source_relabeling_and_new_epoch_fail_closed")
        public = {"status": "SYNTHETIC_PG_MECHANICS_VERIFIED", "checks": self.completed,
            "production_approval_created": False, "production_writes": 0, "full_financial_import_complete": False,
            "source_provenance_cli_e2e": "NOT_RUN", "product_rebuilt": False}
        W.F.write_private(self.output, "wallet-result.public.json", W.canonical(public) + "\n")
        print(json.dumps(public))


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--fixture", required=True, type=Path)
    p.add_argument("--output", required=True, type=Path)
    a = p.parse_args(argv)
    WalletRegression(W.C.load_json(a.fixture), a.output).run()


if __name__ == "__main__":
    main()
