-- Explicit fresh install after promotions. Component 48 only adds red packets to
-- core_promotions; earlier component SQL stays byte-identical.
-- Red packets are share links over existing redemption codes. Each item binds
-- one code; a claim posts that code's canonical promotion grant to the claimant.
-- Budget stays reserved by the code itself, so a packet never mints new value.
CREATE TABLE core_promotions.red_packets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE CHECK(slug ~ '^[A-Za-z0-9_-]{1,64}$'),
    title TEXT NOT NULL CHECK(char_length(title) BETWEEN 1 AND 80),
    description TEXT NOT NULL DEFAULT '' CHECK(char_length(description)<=500),
    cover_image TEXT NOT NULL DEFAULT '' CHECK(octet_length(cover_image)<=3145728),
    cover_prompt TEXT NOT NULL DEFAULT '' CHECK(char_length(cover_prompt)<=1000),
    draw_mode TEXT NOT NULL CHECK(draw_mode IN ('random','weighted','sequence')),
    per_user_limit INTEGER NOT NULL CHECK(per_user_limit BETWEEN 1 AND 100),
    start_at BIGINT NOT NULL CHECK(start_at>=0),
    end_at BIGINT NOT NULL CHECK(end_at>=0),
    enabled BOOLEAN NOT NULL,
    created_by BIGINT NOT NULL REFERENCES core_identity.users(id),
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    deleted_at BIGINT,
    CHECK(end_at=0 OR start_at=0 OR end_at>start_at)
);
CREATE TABLE core_promotions.red_packet_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    packet_id BIGINT NOT NULL REFERENCES core_promotions.red_packets(id),
    code_digest BYTEA NOT NULL REFERENCES core_promotions.codes(digest),
    weight INTEGER NOT NULL CHECK(weight BETWEEN 1 AND 1000000),
    created_at BIGINT NOT NULL,
    released_at BIGINT
);
CREATE UNIQUE INDEX red_packet_items_live_code ON core_promotions.red_packet_items(code_digest)
    WHERE released_at IS NULL;
CREATE INDEX red_packet_items_packet ON core_promotions.red_packet_items(packet_id,id);
CREATE TABLE core_promotions.red_packet_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    packet_id BIGINT NOT NULL REFERENCES core_promotions.red_packets(id),
    user_id BIGINT NOT NULL REFERENCES core_identity.users(id),
    claim_index INTEGER NOT NULL CHECK(claim_index BETWEEN 1 AND 100),
    -- Imported history keeps its original reward snapshot without a Core grant.
    item_id BIGINT UNIQUE REFERENCES core_promotions.red_packet_items(id),
    promotion_claim_id TEXT UNIQUE REFERENCES core_promotions.claims(id),
    reward JSONB NOT NULL CHECK(jsonb_typeof(reward)='object' AND octet_length(reward::text)<=4096),
    created_at BIGINT NOT NULL,
    UNIQUE(packet_id,user_id,claim_index),
    CHECK((item_id IS NULL)=(promotion_claim_id IS NULL))
);
CREATE FUNCTION core_promotions.guard_red_packet() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
    IF TG_OP='DELETE' OR (NEW.id,NEW.slug,NEW.created_by,NEW.created_at) IS DISTINCT FROM (OLD.id,OLD.slug,OLD.created_by,OLD.created_at)
        OR (OLD.deleted_at IS NOT NULL AND NEW IS DISTINCT FROM OLD) THEN
        RAISE EXCEPTION 'immutable red packet identity' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER red_packet_identity BEFORE UPDATE OR DELETE ON core_promotions.red_packets
    FOR EACH ROW EXECUTE FUNCTION core_promotions.guard_red_packet();
CREATE FUNCTION core_promotions.guard_red_packet_item() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
    IF TG_OP='INSERT' THEN
        IF NEW.released_at IS NOT NULL OR NOT EXISTS(SELECT 1 FROM core_promotions.codes d
            JOIN core_promotions.campaigns c ON c.id=d.campaign_id
            WHERE d.digest=NEW.code_digest AND c.kind='redemption') THEN
            RAISE EXCEPTION 'red packet item must bind a live redemption code' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP='DELETE' OR (to_jsonb(NEW)-'released_at') IS DISTINCT FROM (to_jsonb(OLD)-'released_at')
        OR OLD.released_at IS NOT NULL OR NEW.released_at IS NULL
        OR EXISTS(SELECT 1 FROM core_promotions.red_packet_claims WHERE item_id=OLD.id) THEN
        RAISE EXCEPTION 'red packet item is immutable after claim or release' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER red_packet_item_identity BEFORE INSERT OR UPDATE OR DELETE ON core_promotions.red_packet_items
    FOR EACH ROW EXECUTE FUNCTION core_promotions.guard_red_packet_item();
CREATE TRIGGER red_packet_claim_immutable BEFORE UPDATE OR DELETE ON core_promotions.red_packet_claims
    FOR EACH ROW EXECUTE FUNCTION core_billing.ledger_immutable();
CREATE FUNCTION core_promotions.check_red_packet_claim() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
    IF NEW.item_id IS NOT NULL AND NOT EXISTS(
        SELECT 1 FROM core_promotions.red_packet_items i
        JOIN core_promotions.claims l ON l.code_digest=i.code_digest
        WHERE i.id=NEW.item_id AND i.packet_id=NEW.packet_id AND i.released_at IS NULL
          AND l.id=NEW.promotion_claim_id AND l.actor_user_id=NEW.user_id) THEN
        RAISE EXCEPTION 'red packet claim does not match its code grant' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER red_packet_claim_bound AFTER INSERT ON core_promotions.red_packet_claims
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION core_promotions.check_red_packet_claim();
REVOKE ALL ON core_promotions.red_packets,core_promotions.red_packet_items,
    core_promotions.red_packet_claims FROM PUBLIC;
REVOKE ALL ON SEQUENCE core_promotions.red_packets_id_seq,core_promotions.red_packet_items_id_seq,
    core_promotions.red_packet_claims_id_seq FROM PUBLIC;
REVOKE ALL ON FUNCTION core_promotions.guard_red_packet(),core_promotions.guard_red_packet_item(),
    core_promotions.check_red_packet_claim() FROM PUBLIC;
